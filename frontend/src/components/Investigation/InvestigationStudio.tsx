import React, { useState } from 'react';
import type { Alert, Investigation, TriageStatus } from '../../types';
import { streamInvestigation } from '../../services/streamClient';
import { useAuth } from '../../context/AuthContext';
import { BrainCircuit, Play, ShieldAlert, Clock, RefreshCw, Terminal } from 'lucide-react';

interface InvestigationStudioProps {
  alerts: Alert[];
  selectedAlert: Alert | null;
  onSelectAlert: (alert: Alert) => void;
  investigations: Record<string, Investigation>;
  onSaveInvestigation: (inv: Investigation) => void;
  onUpdateAlertStatus: (alertId: string, status: TriageStatus) => void;
}

export const InvestigationStudio: React.FC<InvestigationStudioProps> = ({
  alerts,
  selectedAlert,
  onSelectAlert,
  investigations,
  onSaveInvestigation,
  onUpdateAlertStatus,
}) => {
  const { demoMode } = useAuth();
  const [isStreaming, setIsStreaming] = useState(false);
  const [streamingText, setStreamingText] = useState('');
  const [highlightedCitation, setHighlightedCitation] = useState<string | null>(null);

  const activeAlert = selectedAlert || (alerts.length > 0 ? alerts[0] : null);
  const existingInvestigation = activeAlert ? investigations[activeAlert.alert_id] : null;

  const handleStartInvestigation = () => {
    if (!activeAlert) return;
    setIsStreaming(true);
    setStreamingText('');

    onUpdateAlertStatus(activeAlert.alert_id, 'investigating');

    streamInvestigation(
      activeAlert.alert_id,
      {
        onChunk: (chunk) => {
          setStreamingText((prev) => prev + chunk);
        },
        onDone: (fullBrief) => {
          setIsStreaming(false);
          const newInv: Investigation = {
            investigation_id: Date.now(),
            alert_id: activeAlert.alert_id,
            status: 'completed',
            incident_brief: fullBrief,
            confidence_score: fullBrief.includes('Critical') ? 'Critical' : 'High',
            citations: [
              {
                alert_id: activeAlert.alert_id,
                claim: activeAlert.description,
                mitre_technique: activeAlert.mitre_technique,
                severity: activeAlert.severity_raw,
              },
            ],
            timeline: [
              { time: activeAlert.timestamp, event: activeAlert.description },
              { time: new Date().toISOString(), event: 'AI Grounded Brief generated by RAG engine' },
            ],
            created_at: new Date().toISOString(),
            completed_at: new Date().toISOString(),
          };
          onSaveInvestigation(newInv);
          onUpdateAlertStatus(activeAlert.alert_id, 'resolved');
        },
        onError: (err) => {
          setIsStreaming(false);
          alert(`Investigation streaming failed: ${err.message}`);
        },
      },
      demoMode
    );
  };

  const displayedBrief = isStreaming ? streamingText : (existingInvestigation?.incident_brief || null);

  // Render text with interactive citations
  const renderBriefWithCitations = (text: string) => {
    const parts = text.split(/(\[alrt_[a-zA-Z0-9_]+\])/g);
    return parts.map((part, index) => {
      const match = part.match(/\[(alrt_[a-zA-Z0-9_]+)\]/);
      if (match) {
        const citedId = match[1];
        const isHovered = highlightedCitation === citedId;
        return (
          <span
            key={index}
            onMouseEnter={() => setHighlightedCitation(citedId)}
            onMouseLeave={() => setHighlightedCitation(null)}
            className={`inline-block font-mono text-xs px-1.5 py-0.5 rounded cursor-pointer transition mx-0.5 border ${
              isHovered
                ? 'bg-cyan-500 text-black border-cyan-400 font-bold shadow-lg shadow-cyan-500/30'
                : 'bg-cyan-950/80 text-cyan-400 border-cyan-800 hover:bg-cyan-900'
            }`}
            title={`Evidence Citation: Traces back to Alert ${citedId}`}
          >
            [{citedId}]
          </span>
        );
      }
      return <span key={index}>{part}</span>;
    });
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
      {/* Left Column: Alert Selector & Context Inspector */}
      <div className="lg:col-span-5 space-y-4">
        {/* Alert Selector Bar */}
        <div className="bg-slate-900 border border-slate-800 p-4 rounded-xl shadow-lg">
          <label className="block text-xs font-mono text-slate-400 uppercase tracking-wider mb-2">
            Target Incident Under Triage
          </label>
          <select
            value={activeAlert?.alert_id || ''}
            onChange={(e) => {
              const selected = alerts.find((a) => a.alert_id === e.target.value);
              if (selected) onSelectAlert(selected);
            }}
            className="w-full bg-slate-950 border border-slate-700 rounded-lg px-3 py-2 text-sm text-slate-200 focus:outline-none focus:border-cyan-500 font-mono"
          >
            {alerts.map((a) => (
              <option key={a.alert_id} value={a.alert_id}>
                [{a.severity_raw.toUpperCase()}] {a.alert_id} - {a.asset_id} ({a.mitre_technique || 'No MITRE'})
              </option>
            ))}
          </select>
        </div>

        {activeAlert && (
          <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 space-y-4 shadow-lg">
            <div className="flex items-center justify-between pb-3 border-b border-slate-800">
              <span className="text-xs font-mono text-slate-400 uppercase tracking-wider flex items-center space-x-1.5">
                <ShieldAlert className="h-4 w-4 text-cyan-400" />
                <span>Evidence Grounding Context</span>
              </span>
              <span className="text-xs px-2 py-0.5 rounded bg-slate-800 border border-slate-700 text-slate-300 font-mono">
                {activeAlert.source}
              </span>
            </div>

            <div>
              <p className="text-xs text-slate-400 font-mono">Description</p>
              <p className="text-sm font-semibold text-slate-100 mt-0.5">{activeAlert.description}</p>
            </div>

            <div className="grid grid-cols-2 gap-3 text-xs font-mono">
              <div className="p-2.5 bg-slate-950/70 border border-slate-800 rounded-lg">
                <span className="text-slate-500">Asset:</span>
                <p className="font-semibold text-slate-200 mt-0.5">{activeAlert.asset_id}</p>
              </div>
              <div className="p-2.5 bg-slate-950/70 border border-slate-800 rounded-lg">
                <span className="text-slate-500">Source IP:</span>
                <p className="font-semibold text-slate-200 mt-0.5">{activeAlert.source_ip || 'N/A'}</p>
              </div>
              <div className="p-2.5 bg-slate-950/70 border border-slate-800 rounded-lg">
                <span className="text-slate-500">MITRE Technique:</span>
                <p className="font-semibold text-cyan-400 mt-0.5">{activeAlert.mitre_technique || 'T1110 (Brute Force)'}</p>
              </div>
              <div className="p-2.5 bg-slate-950/70 border border-slate-800 rounded-lg">
                <span className="text-slate-500">ML FP Likelihood:</span>
                <p className={`font-semibold mt-0.5 ${(activeAlert.false_positive_score || 0) < 0.2 ? 'text-red-400' : 'text-emerald-400'}`}>
                  {((activeAlert.false_positive_score || 0) * 100).toFixed(0)}%
                </p>
              </div>
            </div>

            {/* Raw Log Evidence Box */}
            <div>
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-xs font-mono text-slate-400 flex items-center space-x-1.5">
                  <Terminal className="h-3.5 w-3.5 text-emerald-400" />
                  <span>Grounding Raw Log</span>
                </span>
                {highlightedCitation && (
                  <span className="text-[10px] font-mono text-cyan-400 bg-cyan-950 px-2 py-0.5 rounded border border-cyan-800 animate-pulse">
                    Citation Match Highlighted
                  </span>
                )}
              </div>
              <pre className={`p-3 bg-black/75 rounded-lg border text-xs font-mono whitespace-pre-wrap break-all transition ${
                highlightedCitation ? 'border-cyan-400 ring-2 ring-cyan-500/20 text-cyan-300' : 'border-slate-800 text-emerald-400/90'
              }`}>
                {activeAlert.raw_log}
              </pre>
            </div>
          </div>
        )}
      </div>

      {/* Right Column: AI RAG Investigation Studio & Real-time Stream */}
      <div className="lg:col-span-7 space-y-4">
        <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-xl">
          {/* Header */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 pb-4 border-b border-slate-800">
            <div className="flex items-center space-x-3">
              <div className="p-2.5 rounded-lg bg-cyan-600/20 text-cyan-400 border border-cyan-500/30">
                <BrainCircuit className="h-6 w-6" />
              </div>
              <div>
                <h3 className="text-base font-bold text-white flex items-center space-x-2">
                  <span>Razzaq RAG Investigation Agent</span>
                  <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-purple-950 text-purple-400 border border-purple-800">
                    Groq + ChromaDB
                  </span>
                </h3>
                <p className="text-xs text-slate-400 font-mono">Evidence-Backed Incident Briefing Engine</p>
              </div>
            </div>

            <button
              onClick={handleStartInvestigation}
              disabled={isStreaming || !activeAlert}
              className="flex items-center space-x-2 px-4 py-2 bg-gradient-to-r from-cyan-600 to-blue-600 hover:from-cyan-500 hover:to-blue-500 text-white rounded-lg text-xs font-mono font-semibold transition shadow-lg shadow-cyan-600/20 disabled:opacity-50"
            >
              {isStreaming ? (
                <>
                  <RefreshCw className="h-3.5 w-3.5 animate-spin" />
                  <span>Streaming Brief...</span>
                </>
              ) : (
                <>
                  <Play className="h-3.5 w-3.5" />
                  <span>{existingInvestigation ? 'Re-Run Investigation' : 'Run AI Investigation'}</span>
                </>
              )}
            </button>
          </div>

          {/* Investigation Output Display */}
          <div className="mt-4">
            {displayedBrief ? (
              <div className="space-y-4">
                {/* Confidence Badge */}
                <div className="flex items-center justify-between p-3 bg-slate-950/80 rounded-lg border border-slate-800">
                  <div className="flex items-center space-x-2">
                    <span className="text-xs font-mono text-slate-400">Assessed Severity:</span>
                    <span className="px-2 py-0.5 rounded bg-red-950 text-red-400 border border-red-800 font-mono text-xs font-bold uppercase">
                      {existingInvestigation?.confidence_score || 'High'}
                    </span>
                  </div>
                  <div className="text-[11px] font-mono text-slate-400">
                    Strict Citation Mode: <span className="text-emerald-400">Grounded (No Hallucinations)</span>
                  </div>
                </div>

                {/* Brief Content */}
                <div className="p-4 bg-slate-950 rounded-lg border border-slate-800 font-mono text-xs leading-relaxed text-slate-200 whitespace-pre-wrap">
                  {renderBriefWithCitations(displayedBrief)}
                  {isStreaming && (
                    <span className="inline-block w-2 h-4 bg-cyan-400 ml-1 animate-pulse align-middle" />
                  )}
                </div>

                {/* Reconstructed Attack Timeline */}
                {existingInvestigation && existingInvestigation.timeline && existingInvestigation.timeline.length > 0 && (
                  <div className="mt-4 p-4 bg-slate-950/60 rounded-lg border border-slate-800">
                    <h4 className="text-xs font-mono uppercase tracking-wider text-slate-400 flex items-center space-x-1.5 mb-3">
                      <Clock className="h-3.5 w-3.5 text-cyan-400" />
                      <span>Reconstructed Attack Timeline</span>
                    </h4>
                    <div className="space-y-3 relative pl-4 border-l border-slate-800">
                      {existingInvestigation.timeline.map((item, idx) => (
                        <div key={idx} className="relative">
                          <span className="absolute -left-[21px] top-1 h-2.5 w-2.5 rounded-full bg-cyan-500 border border-slate-900" />
                          <span className="text-[10px] font-mono text-slate-500">
                            {item.time ? new Date(item.time).toLocaleTimeString() : 'T-0'}
                          </span>
                          <p className="text-xs text-slate-300 font-mono mt-0.5">{item.event || item.text}</p>
                        </div>
                      ))}
                    </div>
                  </div>
                )}

                {/* Analyst Resolution Actions */}
                <div className="flex flex-wrap items-center justify-end gap-2 pt-3 border-t border-slate-800">
                  <button
                    onClick={() => activeAlert && onUpdateAlertStatus(activeAlert.alert_id, 'dismissed')}
                    className="px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-300 rounded-lg text-xs font-mono transition"
                  >
                    Dismiss as Benign
                  </button>
                  <button
                    onClick={() => activeAlert && onUpdateAlertStatus(activeAlert.alert_id, 'resolved')}
                    className="px-3 py-1.5 bg-emerald-600/20 hover:bg-emerald-600/30 text-emerald-300 border border-emerald-500/40 rounded-lg text-xs font-mono transition"
                  >
                    Mark Resolved
                  </button>
                </div>
              </div>
            ) : (
              <div className="py-16 text-center text-slate-500 font-mono space-y-2">
                <BrainCircuit className="h-10 w-10 mx-auto text-slate-600" />
                <p className="text-sm text-slate-400">No active investigation running for this alert.</p>
                <p className="text-xs text-slate-500">
                  Click <span className="text-cyan-400 font-semibold">Run AI Investigation</span> above to trigger the RAG agent and stream the grounded incident brief.
                </p>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
